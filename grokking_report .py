#  DATASET HELPERS
# ─────────────────────────────────────────────────────────────────────────────

OP_ADD = "add"   # input op-token = p
OP_MUL = "mul"   # input op-token = p+1

def op_token(p, op):
    return p if op == OP_ADD else p + 1


def make_dataset(p, op):
    """List of (a, op_tok, b, label)."""
    tok  = op_token(p, op)
    data = []
    for a in range(p):
        for b in range(p):
            lbl = (a + b) % p if op == OP_ADD else (a * b) % p
            data.append((a, tok, b, lbl))
    return data


def make_dataset_mul_nonzero(p):
    """
    Multiplication dataset using only nonzero operands: a, b in 1..p-1.

    WHY THIS IS THE ROOT CAUSE OF NON-GROKKING
    ───────────────────────────────────────────
    For a prime p, the multiplicative group (Z_p*, x) is cyclic of order p-1.
    The model generalises multiplication via the discrete-log isomorphism:
        (Z_p*, x)  ~=  (Z_{p-1}, +)  via  a  |->  ind_g(a)
    and then applies the same Fourier-rotation algorithm used for addition.

    When (a=0) or (b=0) pairs are in the dataset, the label is always 0.
    But 0 has NO discrete log and does NOT belong to Z_p*. The model cannot
    handle these pairs with the clean Fourier circuit — it must keep a separate
    memorised lookup for zeros. That lookup raises the weight norm of the
    "generalising" solution above pure memorisation, so weight decay can NEVER
    trigger the cleanup phase. Result: multiplication never groks, regardless
    of how many epochs you train or how high you set wd.

    Excluding zero pairs fixes this: every example fits the discrete-log
    algorithm, the generalising solution has strictly lower weight norm than
    memorisation, weight decay triggers cleanup, both tasks grok.

    Note: for prime p, (a * b) % p != 0 whenever a, b != 0 (no zero divisors),
    so all labels are also in 1..p-1 — fully compatible with the model output.
    """
    tok  = op_token(p, OP_MUL)
    data = []
    for a in range(1, p):          # exclude 0
        for b in range(1, p):      # exclude 0
            lbl = (a * b) % p      # always in 1..p-1 for prime p
            data.append((a, tok, b, lbl))
    return data


def split_dataset(data, frac_train, seed):
    data = list(data)
    random.seed(seed)
    random.shuffle(data)
    div = int(frac_train * len(data))
    return data[:div], data[div:]


def to_tensors(data, device):
    inp = torch.tensor([[a, op, b] for a, op, b, _ in data],
                       dtype=torch.long, device=device)
    lbl = torch.tensor([lbl for *_, lbl in data],
                       dtype=torch.long, device=device)
    return inp, lbl


# ─────────────────────────────────────────────────────────────────────────────
#  MODEL  (one-layer transformer, faithful to Nanda et al. 2023)
# ─────────────────────────────────────────────────────────────────────────────

class Embed(nn.Module):
    def __init__(self, d_vocab, d_model):
        super().__init__()
        self.W_E = nn.Parameter(torch.randn(d_model, d_vocab) / math.sqrt(d_model))
    def forward(self, x):
        return einops.rearrange(self.W_E[:, x], "d b s -> b s d")


class Unembed(nn.Module):
    def __init__(self, d_vocab, d_model):
        super().__init__()
        self.W_U = nn.Parameter(torch.randn(d_model, d_vocab) / math.sqrt(d_vocab))
    def forward(self, x):
        return x @ self.W_U


class PosEmbed(nn.Module):
    def __init__(self, max_ctx, d_model):
        super().__init__()
        self.W_pos = nn.Parameter(torch.randn(max_ctx, d_model) / math.sqrt(d_model))
    def forward(self, x):
        return x + self.W_pos[: x.shape[-2]]


class Attention(nn.Module):
    def __init__(self, d_model, n_heads, d_head, n_ctx):
        super().__init__()
        self.W_K = nn.Parameter(torch.randn(n_heads, d_head, d_model) / math.sqrt(d_model))
        self.W_Q = nn.Parameter(torch.randn(n_heads, d_head, d_model) / math.sqrt(d_model))
        self.W_V = nn.Parameter(torch.randn(n_heads, d_head, d_model) / math.sqrt(d_model))
        self.W_O = nn.Parameter(torch.randn(d_model, d_head * n_heads) / math.sqrt(d_model))
        self.register_buffer("mask", torch.tril(torch.ones(n_ctx, n_ctx)))
        self.d_head = d_head
        # LayerNorm removed — paper uses no LN (Nanda et al. 2023)

    def forward(self, x):
        k   = torch.einsum("ihd,bpd->biph", self.W_K, x)
        q   = torch.einsum("ihd,bpd->biph", self.W_Q, x)
        v   = torch.einsum("ihd,bpd->biph", self.W_V, x)
        sc  = torch.einsum("biph,biqh->biqp", k, q)
        sc  = sc - 1e10 * (1 - self.mask[: x.shape[-2], : x.shape[-2]])
        attn= F.softmax(sc / math.sqrt(self.d_head), dim=-1)
        z   = torch.einsum("biph,biqp->biqh", v, attn)
        return torch.einsum("df,bqf->bqd", self.W_O,
                            einops.rearrange(z, "b i q h -> b q (i h)"))


class MLP(nn.Module):
    def __init__(self, d_model, d_mlp):
        super().__init__()
        # LayerNorm removed — paper uses no LN (Nanda et al. 2023)
        self.W_in  = nn.Parameter(torch.randn(d_mlp, d_model) / math.sqrt(d_model))
        self.b_in  = nn.Parameter(torch.zeros(d_mlp))
        self.W_out = nn.Parameter(torch.randn(d_model, d_mlp) / math.sqrt(d_model))
        self.b_out = nn.Parameter(torch.zeros(d_model))
        self._post = None   # cached for DFT analysis

    def forward(self, x):
        pre = torch.einsum("md,bpd->bpm", self.W_in, x) + self.b_in
        post = F.relu(pre)
        self._post = post.detach()
        return torch.einsum("dm,bpm->bpd", self.W_out, post) + self.b_out


class Transformer(nn.Module):
    """
    Input:  [a, op_token, b]   (seq length 3)
    Output: logits over d_vocab, predict at position 2
    d_vocab = p + 2  (tokens 0..p-1 are numbers; p = '+' token; p+1 = '×' token)
    """
    def __init__(self, p, d_model=128, n_heads=4, n_ctx=3):
        super().__init__()
        d_vocab = p + 2
        d_head  = d_model // n_heads
        self.p  = p
        self.embed     = Embed(d_vocab, d_model)
        self.pos_embed = PosEmbed(n_ctx, d_model)
        self.attn      = Attention(d_model, n_heads, d_head, n_ctx)
        self.mlp       = MLP(d_model, 4 * d_model)
        self.unembed   = Unembed(d_vocab, d_model)
        # ln_out removed — paper uses no LN (Nanda et al. 2023)

    def forward(self, x):
        h = self.embed(x)
        h = self.pos_embed(h)
        h = h + self.attn(h)
        h = h + self.mlp(h)
        return self.unembed(h)  # no final LayerNorm — matches Nanda et al.

    # ── analysis helpers ──────────────────────────────────────────────────────

    @property
    def W_E_np(self):
        """Token embedding matrix, rows = tokens 0..p-1.  Shape (p, d_model)."""
        return self.embed.W_E.detach().T[: self.p].float().cpu().numpy()

    def get_mlp_activations(self, inp):
        """Run forward, return post-ReLU MLP acts at last position.  (N, d_mlp)."""
        self.eval()
        with torch.no_grad():
            self.forward(inp)
        return self.mlp._post[:, -1, :].float().cpu().numpy()


def _raw(model):
    """Unwrap torch.compile wrapper if present."""
    return getattr(model, "_orig_mod", model)


