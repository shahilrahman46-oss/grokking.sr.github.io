def cross_entropy(logits, labels):
    """High-precision cross-entropy (float64 log-softmax)."""
    lp = F.log_softmax(logits.double(), dim=-1)
    return -torch.gather(lp, 1, labels[:, None]).mean()


def accuracy(logits, labels):
    return (logits.argmax(-1) == labels).float().mean().item()


def weight_norm_sq(model):
    return sum(p.detach().float().pow(2).sum().item() for p in model.parameters())


def constant_lr(step, warmup, base_lr):
    """Linear warmup for `warmup` steps, then constant LR — matches Nanda et al. 2023.
    The paper uses LambdaLR(opt, lambda step: min(step/10, 1)).
    """
    return base_lr * min(step / max(warmup, 1), 1.0)


def build_model(p, d_model, device, compile_model=True):
    m = Transformer(p=p, d_model=d_model).to(device)
    if compile_model and device.type == "cuda":
        try:
            # "default" compiles without CUDA Graphs, avoiding the
            # "overwritten tensor output" RuntimeError that "reduce-overhead"
            # triggers when the model is called multiple times per training step.
            m = torch.compile(m, mode="default")
            print("    torch.compile enabled (mode=default)")
        except Exception:
            pass
    return m


# ─────────────────────────────────────────────────────────────────────────────
#  SINGLE-TASK TRAINING
# ─────────────────────────────────────────────────────────────────────────────

def train(p, op, frac_train, epochs, lr, wd, d_model, seed, device,
          use_amp=True, log_every=50, label=""):
    """
    Full-batch training on one operation.
    Returns dict with all metrics + trained model.
    """
    tag = label or f"(a {'+ ' if op==OP_ADD else '× '} b) mod {p}"
    print(f"\n  Training {tag}  [{epochs:,} epochs, device={device}]")

    # ── data ────────────────────────────────────────────────────────────────
    train_data, test_data = split_dataset(make_dataset(p, op), frac_train, seed)
    tr_inp, tr_lbl = to_tensors(train_data, device)
    te_inp, te_lbl = to_tensors(test_data,  device)

    # ── model ───────────────────────────────────────────────────────────────
    model  = build_model(p, d_model, device)
    opt    = optim.AdamW(model.parameters(), lr=lr, weight_decay=wd,
                         betas=(0.9, 0.98), eps=1e-8)
    scaler = torch.amp.GradScaler() if (device.type == "cuda" and use_amp) else None
    warmup = 500  # longer warmup — prevents early spikes with cogrok_lr=5e-4

    # ── metric buffers ───────────────────────────────────────────────────────
    tr_losses, te_losses = [], []
    tr_accs,   te_accs   = [], []
    w_norms,   ckpts     = [], []

    t0 = time.time()
    for ep in range(epochs + 1):

        # ── log ─────────────────────────────────────────────────────────────
        if ep % log_every == 0:
            model.eval()
            with torch.no_grad():
                tr_lg = model(tr_inp)[:, -1]
                te_lg = model(te_inp)[:, -1]
            trl = cross_entropy(tr_lg, tr_lbl).item()
            tel = cross_entropy(te_lg, te_lbl).item()
            tra = accuracy(tr_lg, tr_lbl)
            tea = accuracy(te_lg, te_lbl)
            wn  = weight_norm_sq(model)
            tr_losses.append(trl); te_losses.append(tel)
            tr_accs.append(tra);   te_accs.append(tea)
            w_norms.append(wn);    ckpts.append(ep)

            if ep % (log_every * 10) == 0:
                elapsed = time.time() - t0
                eta     = elapsed / max(ep, 1) * (epochs - ep)
                print(f"    ep {ep:>7,}/{epochs:,} | "
                      f"train {tra:.1%}  test {tea:.1%} | "
                      f"loss {trl:.3f}/{tel:.3f} | "
                      f"{elapsed:.0f}s  ETA {eta:.0f}s")

        if ep == epochs:
            break

        # ── gradient step ────────────────────────────────────────────────────
        new_lr = constant_lr(ep, warmup, lr)
        for g in opt.param_groups:
            g["lr"] = new_lr

        model.train()
        if scaler:
            with torch.amp.autocast(device_type="cuda"):
                loss = cross_entropy(model(tr_inp)[:, -1], tr_lbl)
            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            # grad clipping removed — paper uses no clipping
            scaler.step(opt); scaler.update()
        else:
            loss = cross_entropy(model(tr_inp)[:, -1], tr_lbl)
            loss.backward()
            # grad clipping removed — paper uses no clipping
            opt.step()
        opt.zero_grad(set_to_none=True)

    elapsed = time.time() - t0
    print(f"    Done in {elapsed:.1f}s  |  "
          f"final train {tr_accs[-1]:.1%}  test {te_accs[-1]:.1%}")

    return {
        "model":        model,
        "p":            p,
        "op":           op,
        "train_data":   train_data,
        "test_data":    test_data,
        "tr_losses":    np.array(tr_losses),
        "te_losses":    np.array(te_losses),
        "tr_accs":      np.array(tr_accs),
        "te_accs":      np.array(te_accs),
        "w_norms":      np.array(w_norms),
        "epochs":       np.array(ckpts),
        "elapsed":      elapsed,
    }


# ─────────────────────────────────────────────────────────────────────────────
#  CO-GROKKING  (multi-task: addition + multiplication)
# ─────────────────────────────────────────────────────────────────────────────

def train_multitask(p, frac_train_add, frac_train_mul, epochs, lr, wd, d_model, seed, device,
                    use_amp=True, log_every=50):
    """
    Single model trained simultaneously on addition AND multiplication.

    THREE ROOT CAUSES of non-grokking (all fixed here):

    1. ZERO PAIRS IN MULTIPLICATION  ← critical root cause
       Pairs (a=0,*) or (*,b=0) always give label 0, have no discrete log,
       and cannot be solved by the Fourier circuit. The model keeps a separate
       memorised lookup for them, raising the weight norm of the "generalising"
       solution above pure memorisation. Weight decay never triggers cleanup.
       FIX: use make_dataset_mul_nonzero() — only a,b in 1..p-1.

    2. INSUFFICIENT WEIGHT DECAY
       With two tasks, the memorisation manifold is 2x larger. wd=1.5 does not
       create enough pressure; wd=3.0 does.

    3. GRADIENT IMBALANCE
       One combined shuffled batch mixes gradients. If tasks differ in difficulty
       the easier one dominates. Separate per-task losses fix this.
    """
    print(f"\n  Co-Grokking (Add + Mul)  [{epochs:,} epochs, wd={wd}, device={device}]")
    print(f"  KEY FIX 1: multiplication uses nonzero pairs only (zeros broke grokking)")
    print(f"  KEY FIX 2: separate per-task losses → balanced gradient signal")
    print(f"  KEY FIX 3: wd={wd} (needs >= 2.5 to force dual cleanup)")
    print(f"  Grokking expected: ~40,000-120,000 epochs with wd={wd}")

    # Addition: full dataset (zero is the identity element, fits Fourier alg)
    add_tr, add_te = split_dataset(make_dataset(p, OP_ADD), frac_train_add, seed)

    # Multiplication: NONZERO pairs only — fixes root cause of non-grokking
    mul_tr, mul_te = split_dataset(make_dataset_mul_nonzero(p), frac_train_mul, seed + 1)

    add_tr_inp, add_tr_lbl = to_tensors(add_tr, device)
    add_te_inp, add_te_lbl = to_tensors(add_te, device)
    mul_tr_inp, mul_tr_lbl = to_tensors(mul_tr, device)
    mul_te_inp, mul_te_lbl = to_tensors(mul_te, device)

    model  = build_model(p, d_model, device)
    opt    = optim.AdamW(model.parameters(), lr=lr, weight_decay=wd,
                         betas=(0.9, 0.98), eps=1e-8)
    scaler = torch.amp.GradScaler() if (device.type == "cuda" and use_amp) else None
    warmup = 500  # longer warmup — prevents early spikes with cogrok_lr=5e-4

    add_tr_ls, add_te_ls = [], []
    add_tr_as, add_te_as = [], []
    mul_tr_ls, mul_te_ls = [], []
    mul_tr_as, mul_te_as = [], []
    w_norms, ckpts       = [], []

    t0 = time.time()
    for ep in range(epochs + 1):

        if ep % log_every == 0:
            model.eval()
            with torch.no_grad():
                a_tlg = model(add_tr_inp)[:, -1]
                a_elg = model(add_te_inp)[:, -1]
                m_tlg = model(mul_tr_inp)[:, -1]
                m_elg = model(mul_te_inp)[:, -1]

            add_tr_ls.append(cross_entropy(a_tlg, add_tr_lbl).item())
            add_te_ls.append(cross_entropy(a_elg, add_te_lbl).item())
            add_tr_as.append(accuracy(a_tlg, add_tr_lbl))
            add_te_as.append(accuracy(a_elg, add_te_lbl))
            mul_tr_ls.append(cross_entropy(m_tlg, mul_tr_lbl).item())
            mul_te_ls.append(cross_entropy(m_elg, mul_te_lbl).item())
            mul_tr_as.append(accuracy(m_tlg, mul_tr_lbl))
            mul_te_as.append(accuracy(m_elg, mul_te_lbl))
            w_norms.append(weight_norm_sq(model))
            ckpts.append(ep)

            if ep % (log_every * 10) == 0:
                elapsed = time.time() - t0
                eta     = elapsed / max(ep, 1) * (epochs - ep)
                print(f"    ep {ep:>7,}/{epochs:,} | "
                      f"add {add_te_as[-1]:.1%}  mul {mul_te_as[-1]:.1%} | "
                      f"{elapsed:.0f}s  ETA {eta:.0f}s")

        if ep == epochs:
            break

        new_lr = constant_lr(ep, warmup, lr)
        for g in opt.param_groups:
            g["lr"] = new_lr

        model.train()
        # KEY FIX: compute each task loss separately → equal gradient signal
        if scaler:
            with torch.amp.autocast(device_type="cuda"):
                add_loss = cross_entropy(model(add_tr_inp)[:, -1], add_tr_lbl)
                mul_loss = cross_entropy(model(mul_tr_inp)[:, -1], mul_tr_lbl)
                loss = add_loss + mul_loss
            scaler.scale(loss).backward()
            scaler.unscale_(opt)
            scaler.step(opt); scaler.update()
        else:
            add_loss = cross_entropy(model(add_tr_inp)[:, -1], add_tr_lbl)
            mul_loss = cross_entropy(model(mul_tr_inp)[:, -1], mul_tr_lbl)
            loss = add_loss + mul_loss
            loss.backward()
            opt.step()
        opt.zero_grad(set_to_none=True)

    elapsed = time.time() - t0
    print(f"    Done in {elapsed:.1f}s  |  "
          f"add {add_te_as[-1]:.1%}  mul {mul_te_as[-1]:.1%}")

    return {
        "model":        model,
        "epochs":       np.array(ckpts),
        "add_tr_losses": np.array(add_tr_ls), "add_te_losses": np.array(add_te_ls),
        "add_tr_accs":   np.array(add_tr_as), "add_te_accs":   np.array(add_te_as),
        "mul_tr_losses": np.array(mul_tr_ls), "mul_te_losses": np.array(mul_te_ls),
        "mul_tr_accs":   np.array(mul_tr_as), "mul_te_accs":   np.array(mul_te_as),
        "w_norms":       np.array(w_norms),
        "elapsed":       elapsed,
    }


# ─────────────────────────────────────────────────────────────────────────────
#  FRACTION SWEEP
# ─────────────────────────────────────────────────────────────────────────────

def fraction_sweep(p, op, fracs, epochs, lr, wd, seed, device,
                   gen_thresh=0.95, d_model=64):
    """
    Train a compact model (d_model=64) for each fraction.
    Returns dict: frac → grokking epoch (or None if not reached).
    """
    print(f"\n  Fraction sweep  [{len(fracs)} fractions × {epochs:,} epochs]")
    results = {}
    for frac in fracs:
        tr, te = split_dataset(make_dataset(p, op), frac, seed)
        if not tr or not te:
            results[frac] = None; continue

        tr_inp, tr_lbl = to_tensors(tr, device)
        te_inp, te_lbl = to_tensors(te, device)
        m   = Transformer(p=p, d_model=d_model).to(device)
        opt = optim.AdamW(m.parameters(), lr=lr, weight_decay=wd, betas=(0.9, 0.98))
        sc  = optim.lr_scheduler.LambdaLR(opt, lambda s: min(s / 10, 1))

        ge  = None
        chk = max(1, epochs // 200)
        for ep in range(epochs + 1):
            if ep % chk == 0:
                m.eval()
                with torch.no_grad():
                    tea = accuracy(m(te_inp)[:, -1], te_lbl)
                if tea >= gen_thresh:
                    ge = ep; break
            if ep == epochs:
                break
            m.train()
            loss = cross_entropy(m(tr_inp)[:, -1], tr_lbl)
            loss.backward()
            # grad clipping removed — paper uses no clipping
            opt.step(); sc.step(); opt.zero_grad(set_to_none=True)

        results[frac] = ge
        status = f"grokked @ ep {ge:,}" if ge is not None else f"no grok (>{epochs:,})"
        print(f"    frac={frac:.0%}  {status}")

    return results


# ─────────────────────────────────────────────────────────────────────────────
#  DFT ANALYSIS
# ─────────────────────────────────────────────────────────────────────────────

def compute_dft(res):
    """Compute DFT power spectra of embeddings and MLP neurons."""
    p     = res["p"]
    model = _raw(res["model"])
    W_E   = model.W_E_np                           # (p, d_model)

    # All (a, op, b) pairs for the given operation
    all_data = make_dataset(p, res["op"])
    all_inp, _ = to_tensors(all_data, DEVICE)
    acts = model.get_mlp_activations(all_inp)       # (p², d_mlp)

    # Embedding DFT: along token axis
    ep_s = (np.abs(np.fft.rfft(W_E, axis=0)) ** 2).sum(axis=1)

    # MLP DFT: along a-axis, averaged over b and neurons
    grid = acts.reshape(p, p, -1)                   # (p, p, d_mlp)
    mp_s = (np.abs(np.fft.rfft(grid, axis=0)) ** 2).mean(axis=(1, 2))

    return ep_s, mp_s


# ─────────────────────────────────────────────────────────────────────────────
#  ALGORITHM ANALYSIS  (Part 5 — multiplication)
# ─────────────────────────────────────────────────────────────────────────────

def algorithm_analysis(res):
    p     = res["p"]
    model = _raw(res["model"])
    W_E   = model.W_E_np                           # (p, d_model)

    g   = primitive_root(p)
    phi = p - 1
    dl  = discrete_log_table(p, g)

    # Sort tokens 1..p-1 by discrete log
    tokens   = list(range(1, p))
    dlog_v   = np.array([dl[t] for t in tokens])
    sort_idx = np.argsort(dlog_v)
    W_sorted = W_E[np.array(tokens)[sort_idx]]     # (p-1, d_model)

    # DFT along discrete-log ordering → key frequencies in Z_{p-1}
    power_dl = (np.abs(np.fft.rfft(W_sorted, axis=0)) ** 2).sum(axis=1)

    # Cosine similarity between token embeddings
    norms    = np.linalg.norm(W_E, axis=1, keepdims=True) + 1e-8
    W_norm   = W_E / norms
    cos_sim  = W_norm @ W_norm.T                   # (p, p)

    # Cosine similarity vs. Δ discrete-log
    W_tok    = W_E[tokens] / (np.linalg.norm(W_E[tokens], axis=1, keepdims=True) + 1e-8)
    cos_sub  = W_tok @ W_tok.T                     # (p-1, p-1)
    dlog_diff= np.abs(dlog_v[:, None] - dlog_v[None, :])

    return {
        "g": g, "phi": phi, "dlog": dl,
        "dlog_v": dlog_v, "sort_idx": sort_idx,
        "norms": np.linalg.norm(W_E, axis=1),
        "power_dl": power_dl,
        "cos_sim":  cos_sim,
        "cos_sub":  cos_sub,
        "dlog_diff": dlog_diff,
        "tokens":   tokens,
    }


