def prime_factors(n):
    fs, d = set(), 2
    while d * d <= n:
        while n % d == 0:
            fs.add(d); n //= d
        d += 1
    if n > 1: fs.add(n)
    return fs


def primitive_root(p):
    phi  = p - 1
    facs = prime_factors(phi)
    for g in range(2, p):
        if all(pow(g, phi // f, p) != 1 for f in facs):
            return g
    return 2


def discrete_log_table(p, g):
    """Returns dict: a → k  s.t.  g^k ≡ a (mod p),  for a in 1..p-1."""
    table, cur = {}, 1
    for k in range(p - 1):
        table[cur] = k
        cur = (cur * g) % p
    return table


